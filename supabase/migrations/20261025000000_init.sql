-- Idea Bridge database (Supabase / Postgres).
-- Timestamps are stored as UTC text 'YYYY-MM-DD HH24:MI:SS' so they sort and
-- compare as plain strings. All access goes through the `api` Edge Function
-- (service role); row level security is enabled with no policies, so the
-- public API keys can read or write nothing directly.

create or replace function now_text() returns text
language sql stable as $$ select to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

create or replace function ago_text(secs integer) returns text
language sql stable as $$ select to_char((now() - make_interval(secs => secs)) at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

create table users (
  id integer generated by default as identity primary key,
  name text not null,
  email text,
  role text not null default 'organizer',      -- 'organizer' = Admin, 'visionary' = Idea contributor
  password_hash text,
  home text not null default 'dashboard',
  notify_email integer not null default 1,
  notify_push integer not null default 1,
  created_at text not null default now_text()
);

create table sessions (
  id text primary key,
  user_id integer not null references users(id) on delete cascade,
  device text,
  created_at text not null default now_text(),
  last_seen_at text not null default now_text(),
  expires_at text not null
);

create table login_links (
