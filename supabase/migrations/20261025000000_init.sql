-- Full-text search over ideas, transcripts and tasks. The 'simple' configuration
-- works for any language (Hebrew included); the AI adds synonyms in both languages.
create table search_index (
  entity text not null,
  entity_id integer not null,
  title text not null default '',
  body text not null default '',
  tsv tsvector generated always as (
    setweight(to_tsvector('simple', coalesce(title, '')), 'A') || setweight(to_tsvector('simple', coalesce(body, '')), 'B')
  ) stored,
  primary key (entity, entity_id)
);
create index search_index_tsv on search_index using gin (tsv);

